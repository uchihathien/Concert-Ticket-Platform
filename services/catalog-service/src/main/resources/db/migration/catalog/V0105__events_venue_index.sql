-- Index cho `events.venue_id`.
--
-- PostgreSQL tự tạo index cho PRIMARY KEY và UNIQUE nhưng **không** tạo cho FOREIGN KEY. Một phép
-- soi toàn hệ tìm được 9 khoá ngoại không có index dẫn đầu đúng cột của nó. File này thêm ĐÚNG
-- MỘT, và phần dưới ghi lại vì sao tám cái kia bị từ chối — vì "đã soi và cố ý không làm" là thứ
-- dễ bị người sau soi lại rồi làm thừa.
--
-- Hai truy vấn thật dùng cột này:
--   1. `SELECT count(*) FROM events WHERE venue_id = ? AND status <> 'DRAFT'` — cửa "địa điểm đang
--      bán vé" chặn trước khi cho sửa sơ đồ ghế. Nằm trên đường GHI, nên chậm ở đây là chậm ngay
--      trước mặt ban tổ chức.
--   2. `JOIN events e ON e.venue_id = v.id AND e.status = 'PUBLISHED'` — danh sách địa điểm.
--
-- Index thường, không partial: một mẫu lọc `<> 'DRAFT'` và một mẫu lọc `= 'PUBLISHED'`, và index
-- partial chỉ phục vụ được mẫu thứ hai nếu bộ lập kế hoạch tự chứng minh được phép kéo theo. Đặt
-- cược vào chuyện đó để đổi lấy một index nhỏ hơn không đáng, khi bảng này vốn không lớn.
--
-- ---------------------------------------------------------------------------
-- Tám khoá ngoại còn lại: cố ý KHÔNG thêm index
-- ---------------------------------------------------------------------------
-- Index không miễn phí — nó là một khoản thuế lên mọi lượt ghi vào bảng. Thêm index cho một cột
-- không ai lọc theo là trả thuế mà không mua gì.
--
--   ticket_types.venue_zone_id, venue_zones.source_template_zone_id,
--   invitations.invited_by, revoked_sessions.revoked_by, scanner_access_codes.created_by,
--   journal_entries.reverses_entry_id, payout_batches.payout_account_id
--     → không có truy vấn nào lọc theo chúng, và bảng cha gần như không bao giờ bị xoá dòng.
--
--   seat_holds.event_session_id
--     → đây là cái quan trọng nhất phải KHÔNG thêm. `seat_holds` là bảng ghi nặng nhất của cả hệ
--       trong một đợt mở bán: mỗi lượt giành ghế là một dòng mới. Và không câu truy vấn nào lọc
--       riêng theo cột này — các đường đọc đi qua `idx_hold_expiry` (hết hạn) và `idx_hold_user`
--       (người dùng + suất diễn). Thêm index ở đây là đánh thuế đúng vào đường nóng nhất để đổi
--       lấy một lợi ích không tồn tại.
--
-- Bảng lớn duy nhất trong hệ là `session_seats` (đã 55k dòng chỉ với dữ liệu mẫu), và nó vốn đã
-- có ba index đúng mục đích, gồm cả một partial index cho việc cấp phát vé đứng.

CREATE INDEX idx_events_venue ON events (venue_id);
